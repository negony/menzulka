# -*- coding: utf-8 -*-
"""Создаёт пользовательское описание программы «Мензулка» (.docx)."""
import os
from docx import Document
from docx.shared import Pt, RGBColor, Cm
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.enum.table import WD_TABLE_ALIGNMENT

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs", "Описание_программы_Мензулка.docx")


def read_version():
    """Версия приложения из pubspec.yaml — чтобы описание не отставало."""
    try:
        with open(os.path.join(ROOT, "pubspec.yaml"), encoding="utf-8") as fh:
            for line in fh:
                if line.startswith("version:"):
                    return line.split(":", 1)[1].strip().split("+")[0]
    except OSError:
        pass
    return ""


VERSION = read_version()

ACCENT = RGBColor(0x1F, 0x4E, 0x79)   # тёмно-синий
BODY = RGBColor(0x20, 0x20, 0x20)

doc = Document()

# Базовый стиль
normal = doc.styles["Normal"]
normal.font.name = "Calibri"
normal.font.size = Pt(11)
normal.font.color.rgb = BODY
normal.paragraph_format.space_after = Pt(6)

for h, sz in (("Heading 1", 15), ("Heading 2", 13)):
    st = doc.styles[h]
    st.font.name = "Calibri"
    st.font.size = Pt(sz)
    st.font.bold = True
    st.font.color.rgb = ACCENT

def h1(text):
    doc.add_heading(text, level=1)

def h2(text):
    doc.add_heading(text, level=2)

def p(text, bold=False, italic=False, size=None, color=None, align=None):
    par = doc.add_paragraph()
    run = par.add_run(text)
    run.bold = bold
    run.italic = italic
    if size:
        run.font.size = Pt(size)
    if color:
        run.font.color.rgb = color
    if align:
        par.alignment = align
    return par

def bullets(items):
    for it in items:
        doc.add_paragraph(it, style="List Bullet")

# ── Титул ──────────────────────────────────────────────────────────────
t = p("Мензулка", bold=True, size=28, color=ACCENT, align=WD_ALIGN_PARAGRAPH.CENTER)
t.paragraph_format.space_before = Pt(24)
st = p("Программа для полевых геодезических работ на телефоне, планшете и компьютере",
       italic=True, size=14, align=WD_ALIGN_PARAGRAPH.CENTER)
p("Описание функций и режимов работы", size=12, align=WD_ALIGN_PARAGRAPH.CENTER)
p(f"Версия {VERSION}" if VERSION else "", size=10, align=WD_ALIGN_PARAGRAPH.CENTER)
doc.add_paragraph()

